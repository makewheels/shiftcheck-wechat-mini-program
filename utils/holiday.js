/**
 * 某一天的节假日信息
 * month 是 0-11
 * 返回 { type: '休' | '班' | '', name: 节日名 }
 */
function info(year, month, day) {
  var key = shift.dateKey(year, month, day)
  var yearData = DATA[year]
  if (!yearData) {
    return { type: '', name: '' }
  }
  if (yearData.holidays[key]) {
    return { type: '休', name: yearData.holidays[key] }
  }
  if (yearData.workdays[key]) {
    return { type: '班', name: yearData.workdays[key] }
  }
  return { type: '', name: '' }
}

/**
 * 该年份是否已内置节假日数据
 */
function hasData(year) {
  return !!DATA[year]
}

module.exports = {
  info: info,
  hasData: hasData
}
